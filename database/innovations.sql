CREATE TABLE IF NOT EXISTS activity_days (
 user_id INT NOT NULL, activity_date DATE NOT NULL, PRIMARY KEY(user_id,activity_date),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS challenges (
 id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(150) NOT NULL, prompt TEXT NOT NULL,
 difficulty VARCHAR(30) NOT NULL DEFAULT 'Beginner', active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS challenge_submissions (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, challenge_id INT NOT NULL,
 challenge_date DATE NOT NULL, solution TEXT NOT NULL, review VARCHAR(1000) NULL,
 status ENUM('submitted','approved','needs_work') NOT NULL DEFAULT 'submitted',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE(user_id,challenge_date), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(challenge_id) REFERENCES challenges(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS projects (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, title VARCHAR(150) NOT NULL,
 description TEXT NOT NULL, url VARCHAR(500) NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS project_feedback (
 id INT AUTO_INCREMENT PRIMARY KEY, project_id INT NOT NULL, user_id INT NOT NULL, body TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS activity_feed (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, kind ENUM('topic','project','learning','challenge') NOT NULL,
 title VARCHAR(190) NOT NULL, url VARCHAR(250) NOT NULL, source_id INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS feed_reactions (
 feed_id INT NOT NULL, user_id INT NOT NULL, PRIMARY KEY(feed_id,user_id),
 FOREIGN KEY(feed_id) REFERENCES activity_feed(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, message VARCHAR(250) NOT NULL,
 url VARCHAR(250) NOT NULL, dedupe_key VARCHAR(190) NOT NULL, is_read TINYINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,dedupe_key),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS app_migrations (
 version VARCHAR(50) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
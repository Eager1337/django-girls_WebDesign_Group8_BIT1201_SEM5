CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, role ENUM('member','mentor','admin') NOT NULL DEFAULT 'member',
 active TINYINT NOT NULL DEFAULT 1, bio TEXT, interests VARCHAR(190) NOT NULL DEFAULT 'Web development',
 photo VARCHAR(190), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(150) NOT NULL, description TEXT NOT NULL,
 starts_at DATETIME NOT NULL, location VARCHAR(190) NOT NULL, capacity INT NOT NULL DEFAULT 30
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS registrations (
 user_id INT NOT NULL, event_id INT NOT NULL, attended TINYINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,event_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resources (
 id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(150) NOT NULL, category VARCHAR(80) NOT NULL,
 url VARCHAR(500) NOT NULL, description TEXT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS progress (
 user_id INT NOT NULL, resource_id INT NOT NULL, completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,resource_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(resource_id) REFERENCES resources(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS topics (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, title VARCHAR(150) NOT NULL,
 body TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS replies (
 id INT AUTO_INCREMENT PRIMARY KEY, topic_id INT NOT NULL, user_id INT NOT NULL, body TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(topic_id) REFERENCES topics(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mentorships (
 id INT AUTO_INCREMENT PRIMARY KEY, member_id INT NOT NULL, mentor_id INT NOT NULL,
 message TEXT NOT NULL, status ENUM('pending','accepted','declined') DEFAULT 'pending',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(member_id,mentor_id),
 FOREIGN KEY(member_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(mentor_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_attempts (
 email VARCHAR(190) PRIMARY KEY, attempts INT DEFAULT 0, last_attempt DATETIME NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_log (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, action VARCHAR(190) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;